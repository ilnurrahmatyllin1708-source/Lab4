x= int(input("Введите x: "))
y= int(input('Введите y: '))
if x>0 and y>0: print('Точка находится на 1 четверти')
elif x>0 and y<0: print('Точка находится на 4 четверти')
elif x<0 and y>0: print('Точка находится на 2 четверти')
elif x<0 and y<0: print('Точка находится на 3 четверти')
elif x==0 or y==0: print('Точка находится на оси координат')